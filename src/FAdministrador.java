    // Quita comillas y diagonales para que no rompan la consulta
    private String limpiar(String texto) {
        return texto.replace("", "").replace("", "").trim();
    }

    private void mostrar(String consulta) {
        cnx.entablar(consulta, TEmpleados);
    }

    private String valor(int fila, int columna) {
        Object dato = TEmpleados.getValueAt(fila, columna);
        return dato == null ? "" : dato.toString();
    }

    private void limpiarCampos() {
        TCodigo.setText("");
        TNombre.setText("");
        TUsuario.setText("");
        TClave.setText("");
        CBPuesto.setSelectedIndex(0);
        CBTurno.setSelectedIndex(0);
        CBEstado.setSelectedIndex(0);
    }

    private boolean datosValidos() {
        if (TCodigo.getText().trim().isEmpty() || TNombre.getText().trim().isEmpty()
                || TUsuario.getText().trim().isEmpty() || TClave.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llene todos los campos");
            return false;
        }
        return true;
    }

    private empleado leerEmpleado() {
        return new empleado(TCodigo.getText().trim(), TNombre.getText().trim(),
                CBPuesto.getSelectedItem().toString(), CBTurno.getSelectedItem().toString(),
                TUsuario.getText().trim(), TClave.getText().trim(), CBEstado.getSelectedItem().toString());
    }
    
