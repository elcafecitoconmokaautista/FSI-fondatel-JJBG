    private void BBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BBuscarActionPerformed
        String texto = limpiar(jTextField1.getText());
        if (texto.isEmpty()) {
            mostrar(empleado.todos);
        } else {
            mostrar(String.format(Queries.empleados_buscar, texto));
        }
    }//GEN-LAST:event_BBuscarActionPerformed

    private void BModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BModificarActionPerformed
       if (!datosValidos()) {
            return;
        }
        empleado e = leerEmpleado();
        if (e.actualizar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "Empleado modificado");
            mostrar(empleado.todos);
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo modificar. Revise que el código exista.");
        }
    }//GEN-LAST:event_BModificarActionPerformed

    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistrarActionPerformed
        if (!datosValidos()) {
            return;
        }
        empleado e = leerEmpleado();
        if (e.insertar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "Empleado registrado");
            mostrar(empleado.todos);
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar. Revise que el código no exista.");
        }
    }//GEN-LAST:event_BRegistrarActionPerformed

    private void TEmpleadosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TEmpleadosMouseClicked
        int f = TEmpleados.getSelectedRow();
        if (f < 0) {
            return;
        }
        TCodigo.setText(valor(f, 0));
        TNombre.setText(valor(f, 1));
        CBPuesto.setSelectedItem(valor(f, 2));
        CBTurno.setSelectedItem(valor(f, 3));
        TUsuario.setText(valor(f, 4));
        TClave.setText(valor(f, 5));
        CBEstado.setSelectedItem(valor(f, 6));
    }//GEN-LAST:event_TEmpleadosMouseClicked

